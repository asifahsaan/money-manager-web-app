// Generates src/styles/tokens.css — every Tailwind palette the app uses becomes
// a CSS variable, so one class (e.g. bg-gray-50) renders correctly in light
// AND dark mode. Run: node scripts/build-theme-tokens.cjs
const fs = require('fs');
const path = require('path');
const colors = require('tailwindcss/colors');

const BRAND = 'indigo'; // brand hue: primary-* and legacy amber-* classes map here
const PALETTES = ['red', 'orange', 'yellow', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'violet', 'purple', 'pink', 'rose'];
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
// Dark mode flips tints and deep shades; 400–600 stay so filled buttons keep contrast.
const DARK_MIRROR = { 50: '950', 100: '900', 200: '800', 300: '700', 400: '400', 500: '500', 600: '600', 700: '300', 800: '200', 900: '100', 950: '50' };

const rgb = (hex) => {
  const n = parseInt(hex.replace('#', ''), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

// Neutrals: cool slate in light; hand-tuned so dark "tints" stay just above the card surface.
const GRAY_LIGHT = Object.fromEntries(SHADES.map((s) => [s, rgb(colors.slate[s])]));
const GRAY_DARK = {
  50: '24 30 44', 100: '31 38 54', 200: '44 52 70', 300: '64 73 92', 400: '110 119 138',
  500: '144 153 170', 600: '174 182 197', 700: '203 209 220', 800: '226 230 237', 900: '241 243 247', 950: '248 250 252',
};

const light = [], dark = [];
for (const s of SHADES) {
  light.push(`  --c-gray-${s}: ${GRAY_LIGHT[s]};`);
  dark.push(`  --c-gray-${s}: ${GRAY_DARK[s]};`);
  light.push(`  --c-brand-${s}: ${rgb(colors[BRAND][s])};`);
  dark.push(`  --c-brand-${s}: ${rgb(colors[BRAND][DARK_MIRROR[s]])};`);
  for (const p of PALETTES) {
    light.push(`  --c-${p}-${s}: ${rgb(colors[p][s])};`);
    dark.push(`  --c-${p}-${s}: ${rgb(colors[p][DARK_MIRROR[s]])};`);
  }
}

const css = `/* AUTO-GENERATED by scripts/build-theme-tokens.cjs — do not edit by hand. */
:root {
${light.join('\n')}
}

.dark {
${dark.join('\n')}
}
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'styles', 'tokens.css'), css);
console.log('wrote src/styles/tokens.css');
module.exports = { PALETTES };
